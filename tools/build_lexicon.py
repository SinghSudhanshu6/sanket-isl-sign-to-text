"""Regenerate extension/lib/lexicon.js (from backend/data/vocabulary.csv) and extension/lib/shortcuts.js (from backend/data/shortcuts.csv).
Run after editing either CSV:   python tools/build_lexicon.py
"""
import csv
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
rows = [[r["gloss"], r["english"], r["group"], r["role"], r["kind"]]
        for r in csv.DictReader(open(root / "backend/data/vocabulary.csv", encoding="utf-8"))]
out = root / "extension/lib/lexicon.js"
out.write_text("/* GENERATED by tools/build_lexicon.py from backend/data/vocabulary.csv - do not edit */\n"
               "(typeof window !== 'undefined' ? window : globalThis).SANKET_LEXICON = "
               + json.dumps(rows, ensure_ascii=False) + ";\n", encoding="utf-8")
print("wrote", out, len(rows), "signs")

# shortcuts: a short sign sequence (key) -> the exact sentence to type. Blank rows and rows starting with # are ignored.
sc = [[r["glosses"].strip().upper(), r["sentence"].strip()]
      for r in csv.DictReader(open(root / "backend/data/shortcuts.csv", encoding="utf-8"))
      if (r.get("glosses") or "").strip() and not r["glosses"].lstrip().startswith("#") and (r.get("sentence") or "").strip()]
out2 = root / "extension/lib/shortcuts.js"
out2.write_text("/* GENERATED by tools/build_lexicon.py from backend/data/shortcuts.csv - do not edit */\n"
                "(typeof window !== 'undefined' ? window : globalThis).SANKET_SHORTCUTS = "
                + json.dumps(sc, ensure_ascii=False) + ";\n", encoding="utf-8")
print("wrote", out2, len(sc), "shortcuts")
